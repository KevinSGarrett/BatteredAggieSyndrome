def world_contests() -> list[dict[str, Any]]:
    """The accepted C56 fixture world with three changes: alternate FBS home games are HOME_B (the parent b side at
    home), Alpha (org 1) plays a second 2023 week-0 game on the same date (a latest-prior tie at its first 2023 target)
    and Echo (org 5) loses its 2023 week-0 game (a cold start at its first 2023 target)."""
    rows = rfx.world_contests()
    for row in rows:
        number = int(row["contest_key"].split(":")[1])
        if row["site"] == "HOME_A" and row["a_division_label"] == row["b_division_label"] == "FBS" and number % 2:
            row["site"] = "HOME_B"
    week0 = [r for r in rows if r["season"] == 2023 and r["contest_date"] < "2023-09-01" and r["a_key"] == "org:5"]
    rows = [r for r in rows if r not in week0]
    first_alpha = next(r for r in rows if r["season"] == 2023 and r["contest_date"] < "2023-09-01" and
                       r["a_key"] == "org:1")
    rows.append(rfx.contest("ncaa:9001", 2023, first_alpha["contest_date"], "1", "6", 31, 7))
    return rows


def _rel(path: Path, root: Path) -> str:
    return Path(path).resolve().relative_to(Path(root).resolve()).as_posix()


def _sha(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def _write_json(path: Path, value: Any) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=1) + "\n", encoding="utf-8", newline="\n")
    return path


def plan_for(targets: list[dict[str, Any]], unconfirmed: str, tie_key: str) -> dict[str, str]:
    """The planted provider classes: deterministic targets of the given seasons (never a cold start or the tie)."""
    plan: dict[str, str] = {}
    by_season: dict[int, list[dict[str, Any]]] = {}
    for t in targets:
        if unconfirmed not in (t["a_org_id"], t["b_org_id"]) and t["contest_date"] > f"{t['season']}-09-08" and \
                t["contest_key"] != tie_key:
            by_season.setdefault(t["season"], []).append(t)
    kinds = {2021: ("SITE_DISAGREE", "START_OUTSIDE_WINDOW", "ABSENT"),
             2022: ("DUPLICATED", "MALFORMED", "PARTICIPANTS_DIFFER"),
             2023: ("SEASON_DIFFERS",)}
    for season, names in kinds.items():
        candidates = [t for t in by_season.get(season, []) if t["parent_site"] != "NEUTRAL"]
        for target, kind in zip(candidates, names):
            plan[target["contest_key"]] = kind
    return plan


def build_world(base: Path) -> dict[str, Any]:
    """The accepted builders' world plus the retained-input stand-ins under one data root (``base``)."""
    base = Path(base)
    world = rfx.build_world(base, world_contests())
    ref_contract = rfx.write_contract(base / "rc.json", rfx.contract_for(world))
    code, ref, stderr = rfx.run_build(ref_contract, world, base)
    if code != 0:
        raise AssertionError(f"accepted reference builder refused the fixture: {stderr}")
    world.update(reference_contract=ref_contract, reference_db=rfx.database_of(ref), reference=ref)
    conn = sqlite3.connect(Path(world["history_db"]).as_uri() + "?mode=ro", uri=True)
    targets = [json.loads(r[0]) for r in conn.execute("SELECT record FROM targets ORDER BY ord")]
    labels = {r["contest_key"]: r for r in (json.loads(x[0]) for x in conn.execute(
        "SELECT record FROM target_labels ORDER BY ord"))}
    conn.close()
    world["targets"] = targets
    unconfirmed = unconfirmed_org(targets, labels)
    tie_key = next(k for k, r in labels.items() if r["a_points"] == r["b_points"])
    world.update(unconfirmed_org=unconfirmed, tie_key=tie_key)
    # ---- C38-shaped participant identity bindings (one SCHEDULE_FINGERPRINT_ONLY rule; one org unconfirmed)
    lines = [json.dumps({"_header": {"contract_sha256": world["parent"]["contract_sha256"],
                                     "schema": "BAS-NATIONAL-DI-POPULATION-1", "stage": "program-season"}})]
    for org, cfbd in sorted(CFBD.items()):
        confirmed = org != unconfirmed
        lines.append(json.dumps({"org_id": org, "cfbd_team_id": cfbd if confirmed else None, "n_games": 9,
                                 "name_candidates": [cfbd],
                                 "rule": ("SCHEDULE_FINGERPRINT_ONLY" if org == "3" else "NAME_CONFIRMED_BY_SCHEDULE")
                                 if confirmed else None,
                                 "reason": None if confirmed else "NAME_CANDIDATE_NOT_CONFIRMED_BY_SCHEDULE",
                                 "best_fingerprint": [cfbd, 9], "candidate_fingerprints": {cfbd: 9},
                                 "runner_up_fingerprint": 0}))
    bindings = base / "raw" / "bindings" / "identity_bindings.jsonl.gz"
    bindings.parent.mkdir(parents=True, exist_ok=True)
    bindings.write_bytes(gzip.compress(("\n".join(lines) + "\n").encode("utf-8"), mtime=0))
    # ---- provider games: one capture per season with every planted class
    plan = plan_for(targets, unconfirmed, tie_key)
    world["plan"] = plan
    captures: dict[str, tuple[str, str]] = {}
    for season_text in SEASON_CAPTURES:
        season = int(season_text)
        games = []
        for t in targets:
            if t["season"] != season:
                continue
            kind = plan.get(t["contest_key"])
            if kind == "ABSENT":
                continue
            a, b = t["a_org_id"], t["b_org_id"]
            neutral = t["parent_site"] == "NEUTRAL"
            home, away = (b, a) if t["parent_site"] == "HOME_B" else (a, b)
            if neutral and int(t["contest_key"].split(":")[1]) % 2 == 0:
                home, away = b, a   # a provider home/away designation swap at a neutral site
            start = t["contest_date"] + "T23:30:00.000Z"
            if kind == "START_OUTSIDE_WINDOW":
                start = f"{season}-01-01T00:00:00.000Z"
            row = {"id": int(t["cfbd_game_ids"][0]), "season": season + 1 if kind == "SEASON_DIFFERS" else season,
                   "week": 1, "seasonType": "regular", "startDate": start, "startTimeTBD": False,
                   "neutralSite": True if kind == "SITE_DISAGREE" else neutral, "conferenceGame": False,
                   "attendance": 1000, "venueId": 100, "venue": "Fixture Venue",
                   "homeId": int(CFBD.get(home, "9999")), "homeTeam": home, "homeClassification": "fbs",
                   "awayId": int(CFBD.get(away, "9998")) if kind != "PARTICIPANTS_DIFFER" else 2004,
                   "awayTeam": away, "awayClassification": "fbs", "homePoints": 1, "awayPoints": 0, "notes": None}
            if kind == "MALFORMED":
                row["neutralSite"] = 0
            games.append(row)
            if kind == "DUPLICATED":
                games.append(dict(row))
        games.append({"id": 99999 + season, "season": season, "week": 9, "seasonType": "regular",
                      "startDate": f"{season}-11-01T18:00:00Z", "startTimeTBD": True, "neutralSite": False,
                      "homeId": 2001, "awayId": 2004, "notes": "a provider row no accepted target documents"})
        payload = (json.dumps(games, indent=1) + "\n").encode("utf-8")
        sha = hashlib.sha256(payload).hexdigest()
        path = base / "raw" / "SRC-002" / "games" / f"sha256_{sha}.json"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(payload)
        capture_id = f"cap_fixture{season}"
        _write_json(base / "manifests" / "captures" / "SRC-002" / f"{capture_id}.json", {
            "capture_id": capture_id, "request_id": f"req_fixture{season}",
            "source_uri": f"https://api.collegefootballdata.com/games?classification=fbs&year={season}",
            "parameters": {"classification": "fbs", "year": season_text}, "http_status": 200, "result": "SUCCESS",
            "response_sha256": sha, "response_bytes": len(payload), "row_count": len(games),
            "capture_known_at_utc": "2026-08-09T18:59:49Z", "retrieved_at_utc": "2026-08-09T18:59:49Z",
            "upstream_lineage": "CFBD_AGGREGATED_OR_DERIVED_RECORD; NOT_AN_INDEPENDENT_CONFIRMATION_OF_ITS_UPSTREAM_SOURCE",
            "immutable_path": f"raw/SRC-002/games/sha256_{sha}.json"})
        captures[season_text] = (sha, capture_id)
    world.update(data_root=base, bindings=bindings, captures=captures)
