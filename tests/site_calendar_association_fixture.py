def unconfirmed_org(targets: list[dict[str, Any]], labels: dict[str, dict[str, Any]]) -> str:
    """The FBS org whose participant binding is planted schedule-unconfirmed (every game of it is outside common
    support): the first that does not play the tie target, so the tie stays inside the common cohort."""
    tie = next(t for t in targets if labels[t["contest_key"]]["a_points"] == labels[t["contest_key"]]["b_points"])
    return next(org for org in FBS_ORGS if org not in (tie["a_org_id"], tie["b_org_id"]) and org != "697")


